#!/usr/bin/env python3
"""Generate an importable, deterministic build identity, not a deployment receipt.

Read actual publication assets; git describes this checkout's base and dirtiness.
No environment/version hints, timestamps, paths or diagnostics enter the artifact.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

CODE_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CODE_ROOT / 'web/scripts'))
sys.path.insert(0, str(CODE_ROOT / 'services/api/src'))
from publish_manifest import MANIFEST, generate
from tcmkb_api.build_info import SCHEMA, normalize_build_info


def git_identity(root: Path) -> tuple[str, bool | None]:
    def git(*args):
        return subprocess.run(['git', *args], cwd=root, capture_output=True, text=True,
                              check=True, timeout=10).stdout.strip()
    try:
        # Never silently claim an enclosing, unrelated repository's HEAD.
        if Path(git('rev-parse', '--show-toplevel')).resolve() != root.resolve():
            return 'unknown', None
        sha = git('rev-parse', '--verify', 'HEAD')
        dirty = bool(git('status', '--porcelain', '--untracked-files=normal'))
        return sha, dirty
    except (OSError, subprocess.SubprocessError, ValueError):
        return 'unknown', None


def build_metadata(root: Path, dist: Path | None = None) -> dict:
    publication = generate(root)
    rendered = json.dumps(publication, ensure_ascii=False, indent=2) + '\n'
    if (root / MANIFEST).read_text(encoding='utf-8') != rendered:
        raise ValueError('stale publication')
    if dist is not None:
        for lecture in publication['lectures']:
            for asset in lecture.get('assets', {}).values():
                path = Path(asset['path'])
                if path.is_relative_to('web/public'):
                    built = dist / path.relative_to('web/public')
                    if hashlib.sha256(built.read_bytes()).hexdigest() != asset['sha256']:
                        raise ValueError('built publication mismatch')
    sha, dirty = git_identity(root)
    return {'schema': SCHEMA, **normalize_build_info({
        'schema': SCHEMA, 'git_sha': sha, 'git_dirty': dirty,
        'content_revision': publication['content_sha256'],
    })}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=CODE_ROOT)
    parser.add_argument('--out', type=Path)
    parser.add_argument('--dist', type=Path, help='verify built public asset bytes before identity injection')
    args = parser.parse_args()
    try:
        metadata = build_metadata(args.root, args.dist)
        dest = args.out or args.root / 'services/worker/src/build_info.py'
        dest.parent.mkdir(parents=True, exist_ok=True)
        # repr of only validated primitive values is a Python literal, not input code.
        text = '# Generated by build_metadata.py; not proof of deployment.\nBUILD_INFO = ' + repr(metadata) + '\n'
        temp = dest.with_suffix('.tmp')
        try:
            temp.write_text(text, encoding='utf-8')
            temp.replace(dest)
        finally:
            temp.unlink(missing_ok=True)
        print('build metadata generated')
        return 0
    except (OSError, ValueError, KeyError, TypeError):
        # Do not copy arbitrary JSON values, filesystem paths or git stderr into output.
        print('build metadata failed: publication or output validation failed', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
